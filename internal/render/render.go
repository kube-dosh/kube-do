// Package render turns cluster.yaml plus a Resource Manifest into Ansible input.
package render

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"gopkg.in/yaml.v3"

	"github.com/kube-dosh/kube-do/internal/cluster"
	"github.com/kube-dosh/kube-do/internal/layout"
	"github.com/kube-dosh/kube-do/internal/manifest"
)

// Render writes inventory.ini and group_vars/all.yml into outDir.
func Render(cfg *cluster.Config, m *manifest.Manifest, outDir string) ([]string, error) {
	if err := os.MkdirAll(filepath.Join(outDir, "group_vars"), 0o755); err != nil {
		return nil, fmt.Errorf("create output directory: %w", err)
	}

	files := []string{
		filepath.Join(outDir, "inventory.ini"),
		filepath.Join(outDir, "group_vars", "all.yml"),
	}

	inventory := buildInventory(cfg)
	if err := os.WriteFile(files[0], []byte(inventory), 0o644); err != nil {
		return nil, fmt.Errorf("write inventory: %w", err)
	}

	vars, err := buildVars(cfg, m)
	if err != nil {
		return nil, err
	}
	body, err := yaml.Marshal(vars)
	if err != nil {
		return nil, fmt.Errorf("encode group vars: %w", err)
	}
	if err := os.WriteFile(files[1], body, 0o600); err != nil {
		return nil, fmt.Errorf("write group vars: %w", err)
	}
	return files, nil
}

func buildInventory(cfg *cluster.Config) string {
	var b strings.Builder
	b.WriteString("# Generated by kube-do. Do not edit.\n\n")
	b.WriteString("[installer]\nlocalhost ansible_connection=local\n\n")
	b.WriteString("[control_plane]\n")
	for _, n := range cfg.ControlPlane.Nodes {
		writeNode(&b, cfg, n)
	}
	b.WriteString("\n[workers]\n")
	if len(cfg.Workers) == 0 {
		b.WriteString("# no workers\n")
	}
	for _, n := range cfg.Workers {
		writeNode(&b, cfg, n)
	}
	b.WriteString("\n[k8s_cluster:children]\ncontrol_plane\nworkers\n")
	return b.String()
}

func writeNode(b *strings.Builder, cfg *cluster.Config, n cluster.Node) {
	fmt.Fprintf(b, "%s ansible_host=%s ansible_user=%s ansible_port=%d kube-do_node_ip=%s",
		n.Name, n.Address, cfg.SSH.User, cfg.SSH.Port, n.Address)
	if cfg.SSH.PrivateKeyFile != "" {
		fmt.Fprintf(b, " ansible_ssh_private_key_file=%s", cfg.SSH.PrivateKeyFile)
	}
	b.WriteByte('\n')
}

type binaryVars struct {
	Name        string `yaml:"name"`
	Version     string `yaml:"version"`
	OS          string `yaml:"os"`
	Arch        string `yaml:"arch"`
	URL         string `yaml:"url"`
	SHA256      string `yaml:"sha256,omitempty"`
	Archive     string `yaml:"archive,omitempty"`
	Built       bool   `yaml:"built,omitempty"`
	ChecksumURL string `yaml:"checksumUrl,omitempty"`
}

type imageVars struct {
	Name       string `yaml:"name"`
	Source     string `yaml:"source"`
	Target     string `yaml:"target"`
	Repository string `yaml:"repository"`
	Tag        string `yaml:"tag"`
}

type installerImageVars struct {
	Name       string `yaml:"name"`
	Version    string `yaml:"version"`
	OS         string `yaml:"os"`
	Arch       string `yaml:"arch"`
	Target     string `yaml:"target"`
	Repository string `yaml:"repository"`
	Tag        string `yaml:"tag"`
	Binary     string `yaml:"binary"`
}

type nodeVars struct {
	Name    string `yaml:"name"`
	Address string `yaml:"address"`
}

type vars struct {
	KubeDoBuild             string               `yaml:"kube-do_build"`
	ClusterName             string               `yaml:"cluster_name"`
	KubernetesVersion       string               `yaml:"kubernetes_version"`
	PlatformOSFamily        string               `yaml:"platform_os_family"`
	PlatformArch            string               `yaml:"platform_arch"`
	SSHUser                 string               `yaml:"ssh_user"`
	SSHPort                 int                  `yaml:"ssh_port"`
	SSHPrivateKeyFile       string               `yaml:"ssh_private_key_file,omitempty"`
	InstallerAddress        string               `yaml:"installer_address"`
	DownloadServer          string               `yaml:"download_server"`
	RegistryAddress         string               `yaml:"registry_address"`
	RegistryNamespace       string               `yaml:"registry_namespace"`
	RegistryDataDir         string               `yaml:"registry_data_dir"`
	RegistryTLSMode         string               `yaml:"registry_tls_mode"`
	RegistryCAFile          string               `yaml:"registry_ca_file,omitempty"`
	RegistryCertFile        string               `yaml:"registry_cert_file,omitempty"`
	RegistryKeyFile         string               `yaml:"registry_key_file,omitempty"`
	ControlPlaneVIP         string               `yaml:"control_plane_vip"`
	ControlPlaneAPIPort     int                  `yaml:"control_plane_api_port"`
	ControlPlaneEndpoint    string               `yaml:"control_plane_endpoint"`
	ControlPlaneAddress     string               `yaml:"control_plane_address"`
	ControlPlaneNodes       []nodeVars           `yaml:"control_plane_nodes"`
	WorkerNodes             []nodeVars           `yaml:"worker_nodes"`
	VRRPRouterID            int                  `yaml:"control_plane_vrrp_router_id"`
	VRRPPassword            string               `yaml:"control_plane_vrrp_password"`
	CNIName                 string               `yaml:"cni_name"`
	CNIKubeProxyReplacement bool                 `yaml:"cni_kube_proxy_replacement"`
	PodCIDR                 string               `yaml:"pod_cidr"`
	ServiceCIDR             string               `yaml:"service_cidr"`
	ClusterDomain           string               `yaml:"cluster_domain"`
	Binaries                []binaryVars         `yaml:"binaries"`
	InstallerBinaries       []binaryVars         `yaml:"installer_binaries,omitempty"`
	InstallerImages         []installerImageVars `yaml:"installer_images,omitempty"`
	Images                  []imageVars          `yaml:"images"`
}

func buildVars(cfg *cluster.Config, m *manifest.Manifest) (*vars, error) {
	v := &vars{
		KubeDoBuild:             m.Metadata.Name,
		ClusterName:             cfg.Metadata.Name,
		KubernetesVersion:       m.Metadata.KubernetesVersion,
		PlatformOSFamily:        cfg.Platform.OSFamily,
		PlatformArch:            cfg.Platform.Arch,
		SSHUser:                 cfg.SSH.User,
		SSHPort:                 cfg.SSH.Port,
		SSHPrivateKeyFile:       cfg.SSH.PrivateKeyFile,
		InstallerAddress:        cfg.Installer.Address,
		DownloadServer:          cfg.DownloadBaseURL(),
		RegistryAddress:         cfg.Registry.Address,
		RegistryNamespace:       m.Spec.Registry.Namespace,
		RegistryDataDir:         cfg.Registry.DataDir,
		RegistryTLSMode:         cfg.Registry.TLS.Mode,
		RegistryCAFile:          cfg.RegistryCAPath(),
		RegistryCertFile:        cfg.Registry.TLS.CertFile,
		RegistryKeyFile:         cfg.Registry.TLS.KeyFile,
		ControlPlaneVIP:         cfg.ControlPlane.VIP,
		ControlPlaneAPIPort:     cfg.ControlPlane.APIPort,
		ControlPlaneEndpoint:    cfg.ControlPlaneEndpoint(),
		ControlPlaneAddress:     cfg.ControlPlaneAddress(),
		VRRPRouterID:            cfg.ControlPlane.VRRP.RouterID,
		VRRPPassword:            cfg.ControlPlane.VRRP.Password,
		CNIName:                 cfg.CNI.Name,
		CNIKubeProxyReplacement: cfg.KubeProxyReplacementEnabled(),
		PodCIDR:                 cfg.CNI.PodCIDR,
		ServiceCIDR:             cfg.CNI.ServiceCIDR,
		ClusterDomain:           cfg.CNI.ClusterDomain,
	}
	for _, n := range cfg.ControlPlane.Nodes {
		v.ControlPlaneNodes = append(v.ControlPlaneNodes, nodeVars{Name: n.Name, Address: n.Address})
	}
	for _, n := range cfg.Workers {
		v.WorkerNodes = append(v.WorkerNodes, nodeVars{Name: n.Name, Address: n.Address})
	}
	platformOS := cfg.Platform.ManifestOS()
	if !m.SupportsPlatform(platformOS, cfg.Platform.Arch) {
		return nil, fmt.Errorf("build %q does not support target platform %s/%s", m.Metadata.Name, platformOS, cfg.Platform.Arch)
	}
	nodeBinaries := m.BinariesFor(platformOS, cfg.Platform.Arch)
	installerBinaries := m.InstallerBinariesFor(platformOS, cfg.Platform.Arch)
	if len(nodeBinaries) == 0 {
		return nil, fmt.Errorf("build %q has no node binaries for %s/%s", m.Metadata.Name, platformOS, cfg.Platform.Arch)
	}
	if len(installerBinaries) == 0 {
		return nil, fmt.Errorf("build %q has no installer binaries for %s/%s", m.Metadata.Name, platformOS, cfg.Platform.Arch)
	}
	for _, b := range nodeBinaries {
		v.Binaries = append(v.Binaries, toBinaryVars(cfg.DownloadBaseURL(), m.Metadata.Name, b))
	}
	for _, b := range installerBinaries {
		v.InstallerBinaries = append(v.InstallerBinaries, toBinaryVars(cfg.DownloadBaseURL(), m.Metadata.Name, b))
	}
	for _, img := range m.InstallerImagesFor(platformOS, cfg.Platform.Arch) {
		ref, err := img.TargetRef(cfg.Registry.Address, m.Spec.Registry.Namespace)
		if err != nil {
			return nil, fmt.Errorf("Installer image %q: %w", img.Name, err)
		}
		repository, tag, err := splitImageRef(ref)
		if err != nil {
			return nil, fmt.Errorf("Installer image %q: %w", img.Name, err)
		}
		v.InstallerImages = append(v.InstallerImages, installerImageVars{
			Name:       img.Name,
			Version:    img.Version,
			OS:         img.OS,
			Arch:       img.Arch,
			Target:     ref,
			Repository: repository,
			Tag:        tag,
			Binary:     img.Binary,
		})
	}
	for _, img := range m.Spec.Images {
		ref, err := img.TargetRef(cfg.Registry.Address, m.Spec.Registry.Namespace)
		if err != nil {
			return nil, fmt.Errorf("image %q: %w", img.Name, err)
		}
		repository, tag, err := splitImageRef(ref)
		if err != nil {
			return nil, fmt.Errorf("image %q: %w", img.Name, err)
		}
		v.Images = append(v.Images, imageVars{Name: img.Name, Source: img.Source, Target: ref, Repository: repository, Tag: tag})
	}
	return v, nil
}

func splitImageRef(ref string) (repository, tag string, err error) {
	colon := strings.LastIndex(ref, ":")
	slash := strings.LastIndex(ref, "/")
	if colon <= slash || colon == len(ref)-1 {
		return "", "", fmt.Errorf("image reference %q must be tagged", ref)
	}
	return ref[:colon], ref[colon+1:], nil
}

func toBinaryVars(baseURL, build string, b manifest.Binary) binaryVars {
	v := binaryVars{
		Name:    b.Name,
		Version: b.Version,
		OS:      b.OS,
		Arch:    b.Arch,
		URL:     layout.BinaryURL(baseURL, build, b),
		SHA256:  b.SHA256,
		Archive: b.Archive,
		Built:   b.IsBuilt(),
	}
	if b.IsBuilt() {
		v.ChecksumURL = layout.BinaryChecksumURL(baseURL, build, b)
	}
	return v
}
